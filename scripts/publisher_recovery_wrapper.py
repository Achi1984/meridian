"""Controlled one-shot adapter, inert on import; no CLI or automatic caller.

Only an externally authenticated trusted owner-session launcher may call this.
Scope fields and window callback bind/check that launcher's decision; they DO
NOT authenticate it. Launcher must verify this wrapper before importing it and
keep source/runtime/exclusive-owner window trusted throughout. No setup follows.
"""
import builtins
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys
import threading
import time
import types

FILES = ('publisher_recovery_wrapper.py', 'publisher_owner_path.py',
         'publisher_marker_recovery.py', 'publisher_test_reconcile.py',
         'publisher_test_auto_setup.py', 'publisher_test_password_setup.py',
         'publisher-test-password-setup-requirements.txt',
         'publisher-test-password-setup-cp314-linux-x86_64.lock')
FAILED_FILES = ('publisher_test_auto_setup.py', 'publisher_test_password_setup.py',
                'publisher-test-password-setup-requirements.txt',
                'publisher-test-password-setup-cp314-linux-x86_64.lock')
BLOCKED = 'OWNER_RECOVERY_BLOCKED'
UNCERTAIN = 'OWNER_RECOVERY_RECONCILIATION_REQUIRED'
COMPLETE = 'OWNER_RECOVERY_ARCHIVED_NO_SETUP_AUTHORIZED'
_USED = False


def _digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def _manifest(value, names):
    if type(value) is not dict or set(value) != set(names):
        raise ValueError('manifest schema')
    if any(type(v) is not str or re.fullmatch('[0-9a-f]{64}', v) is None for v in value.values()):
        raise ValueError('manifest digest')


def _source_bytes(manifest):
    """Pins are independently reviewed inputs, never generated by this adapter."""
    _manifest(manifest, FILES)
    root = Path(__file__).absolute().parent
    result = {}
    for name in FILES:
        fd = os.open(root / name, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
        try:
            info = os.fstat(fd)
            if (not stat.S_ISREG(info.st_mode) or info.st_uid not in (0, os.getuid())
                    or info.st_mode & 0o022 or info.st_size > 262144):
                raise ValueError('source file')
            data = os.read(fd, 262145)
            if (len(data) != info.st_size or os.read(fd, 1)
                    or hashlib.sha256(data).hexdigest() != manifest[name]):
                raise ValueError('source changed')
            result[name] = data
        finally:
            os.close(fd)
    return result


def _modules(source):
    loaded = {}
    original_import = builtins.__import__
    def verified_import(name, globals=None, locals=None, fromlist=(), level=0):
        if name == 'publisher_marker_recovery' and level == 0:
            return loaded[name]
        return original_import(name, globals, locals, fromlist, level)
    for name in ('publisher_marker_recovery', 'publisher_owner_path',
                 'publisher_test_password_setup', 'publisher_test_auto_setup',
                 'publisher_test_reconcile'):
        module = types.ModuleType(name)
        module.__file__ = str(Path(__file__).absolute().with_name(name + '.py'))
        module.__dict__['__builtins__'] = dict(vars(builtins), __import__=verified_import)
        exec(compile(source[name + '.py'], module.__file__, 'exec'), module.__dict__)
        loaded[name] = module
    auto = loaded['publisher_test_auto_setup']
    original = loaded['publisher_test_password_setup']
    auto.load_original = lambda: original
    loaded['publisher_test_reconcile'].load_auto = lambda: auto
    return loaded


def _scope(scope, manifest, failed, argv):
    keys = {'action', 'owner_id', 'operation_id', 'window_id', 'expires_at',
            'source_manifest_sha256', 'failed_manifest_sha256', 'argv_sha256',
            'marker', 'approval_comment_id', 'reconciliation_comment_id', 'baseline_sha256'}
    if type(scope) is not dict or set(scope) != keys:
        raise ValueError('scope schema')
    if scope['action'] != 'ARCHIVE_PUBLISHER_ATTEMPT_ONCE' or type(scope['owner_id']) is not int or scope['owner_id'] != 319562141:
        raise ValueError('scope identity or action')
    for key in ('operation_id', 'window_id'):
        if type(scope[key]) is not str or re.fullmatch('[a-f0-9]{32}', scope[key]) is None:
            raise ValueError('operation/window')
    if (type(scope['expires_at']) is not int
            or not 0 < scope['expires_at'] - time.time() <= 300):
        raise ValueError('expired scope')
    if (scope['source_manifest_sha256'] != _digest(manifest)
            or scope['failed_manifest_sha256'] != _digest(failed)
            or scope['argv_sha256'] != _digest(argv)):
        raise ValueError('scope source/arguments')
    return {'operation_id': scope['operation_id'],
            'reviewed_source_sha256': _digest(manifest),
            'failed_source_sha256': _digest(failed),
            'approval_comment_id': scope['approval_comment_id'],
            'reconciliation_comment_id': scope['reconciliation_comment_id']}


def _baseline(scope, argv):
    if argv.count('--baseline') != 1 or any(arg.startswith('--baseline=') for arg in argv):
        raise ValueError('baseline argument')
    path = Path(argv[argv.index('--baseline') + 1])
    if not path.is_absolute():
        raise ValueError('baseline path')
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        info = os.fstat(fd)
        if (not stat.S_ISREG(info.st_mode) or info.st_uid not in (0, os.getuid())
                or info.st_mode & 0o022 or info.st_size > 262144
                or hashlib.sha256(os.read(fd, 262145)).hexdigest() != scope['baseline_sha256']):
            raise ValueError('baseline pin')
    finally:
        os.close(fd)


def _archive(recovery, directory, scope, record):
    archive_name = 'recovery-' + scope['operation_id']
    fd = os.open(archive_name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=directory)
    try:
        archive = recovery._directory(fd)
        moved = recovery.inspect_marker(fd)
        if any(moved[key] != value for key, value in scope['marker'].items() if key != 'st_ctime_ns'):
            raise ValueError('archived marker identity')
        evidence = os.open('evidence.json', os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=fd)
        try:
            info = os.fstat(evidence)
            expected = recovery._record(record, scope['marker'])
            if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid()
                    or stat.S_IMODE(info.st_mode) != 0o600 or info.st_nlink != 1
                    or info.st_size != len(expected) or os.read(evidence, len(expected)+1) != expected):
                raise ValueError('archive evidence')
            named = os.stat('evidence.json', dir_fd=fd, follow_symlinks=False)
            if (named.st_dev, named.st_ino) != (info.st_dev, info.st_ino):
                raise ValueError('evidence detached')
        finally:
            os.close(evidence)
        named = os.stat(archive_name, dir_fd=directory, follow_symlinks=False)
        if (named.st_dev, named.st_ino) != (archive.st_dev, archive.st_ino):
            raise ValueError('archive detached')
        try:
            os.stat(recovery.MARKER, dir_fd=directory, follow_symlinks=False)
        except FileNotFoundError:
            return
        raise ValueError('new marker')
    finally:
        os.close(fd)


def run_approved_recovery(manifest=None, failed_manifest=None, scope=None,
                          reconcile_argv=None, window_check=None):
    """Return 0 only after bounded COMPLETE delivery; caller must exit with it.

    No arguments means blocked. Caller-supplied data/callback are NOT authority.
    ``reconcile.main`` return 0 is an in-process return code, not an observed
    outer process exit. Its unchanged supervised DB child verifies its own exit.
    The launcher must observe this process's final status AND zero OS exit.
    Any absent output/exception/nonzero exit requires read-only reconciliation.
    """
    global _USED
    if _USED:
        return 1
    _USED = True
    outcome = BLOCKED
    original = None
    attempted = False
    reconciliation_started = False
    old_umask = None
    try:
        if (sys.platform != 'linux' or sys.flags.isolated != 1
                or threading.active_count() != 1 or not callable(window_check)
                or type(reconcile_argv) is not list
                or any(type(arg) is not str for arg in reconcile_argv)):
            raise ValueError('controlled invocation')
        _manifest(failed_manifest, FAILED_FILES)
        _manifest(manifest, FILES)
        # Freeze the decision inputs before any callback or helper executes.
        manifest = dict(manifest)
        failed_manifest = dict(failed_manifest)
        scope = json.loads(json.dumps(scope))
        reconcile_argv = list(reconcile_argv)
        record = _scope(scope, manifest, failed_manifest, reconcile_argv)
        source = _source_bytes(manifest)
        modules = _modules(source)
        original = modules['publisher_test_password_setup']
        recovery = modules['publisher_marker_recovery']
        paths = modules['publisher_owner_path']
        reconciliation = modules['publisher_test_reconcile']
        recovery._record(record, scope['marker'])
        def current():
            if time.time() >= scope['expires_at'] or window_check(scope['window_id']) is not True:
                raise ValueError('exclusive window no longer confirmed')
        current()
        _baseline(scope, reconcile_argv)
        with paths.open_owner_directory() as (directory, revalidate):
            if recovery.inspect_marker(directory) != scope['marker']:
                raise ValueError('approved marker changed')
            statuses = []
            emit = original.emit_status
            def observed(outcome):
                delivered = emit(outcome)
                statuses.append((outcome, delivered))
                return delivered
            original.emit_status = observed
            try:
                reconciliation_started = True
                result = reconciliation.main(reconcile_argv)
            finally:
                original.emit_status = emit
            if type(result) is not int or result != 0 or statuses != [(reconciliation.OK, True)]:
                raise ValueError('reconciliation status or return code')
            current()
            _source_bytes(manifest)
            _baseline(scope, reconcile_argv)
            revalidate()
            if recovery.inspect_marker(directory) != scope['marker']:
                raise ValueError('marker changed during reconciliation')
            # This adapter is only for a dedicated, single-threaded process.
            old_umask = os.umask(0o077)
            attempted = True
            if recovery.retire_marker(directory, scope['marker'], record) != recovery.RETIRED:
                raise ValueError('retirement incomplete')
            current()
            revalidate()
            _archive(recovery, directory, scope, record)
            current()
            _source_bytes(manifest)
        os.umask(old_umask)
        old_umask = None
        outcome = COMPLETE
    except BaseException:
        outcome = UNCERTAIN if attempted or reconciliation_started else BLOCKED
    finally:
        if old_umask is not None:
            try:
                os.umask(old_umask)
            except BaseException:
                outcome = UNCERTAIN
    try:
        delivered = original is not None and original.emit_status(outcome) is True
    except BaseException:
        delivered = False
    return 0 if delivered and outcome == COMPLETE else 1
